//! `cargo xtask api`: generates the Python API methods and the API guide from the
//! command registry. `--check` fails if the committed files are out of date.

use std::fmt::Write as _;
use std::path::PathBuf;

use CosmicCAM_engine::{CommandSpec, Param, ParamKind, Session, cmd};

const PY_OUT: &str = "python/cosmiccam/_commands.py";
const GUIDE_OUT: &str = "docs/api/python.md";
const GUIDE_INTRO: &str = "docs/api/_intro.md";

pub fn run(check: bool) -> Result<(), String> {
    println!("==> api{}", if check { " --check" } else { "" });
    let root = crate::root();
    let commands: Vec<&CommandSpec> = cmd::all().filter(|c| !c.id.starts_with("test.")).collect();
    let intro = std::fs::read_to_string(root.join(GUIDE_INTRO)).map_err(|e| format!("{GUIDE_INTRO}: {e}"))?;
    let outputs = [(PY_OUT, python(&commands)), (GUIDE_OUT, guide(&intro, &commands))];
    let mut stale = Vec::new();
    for (rel, text) in outputs {
        let path: PathBuf = root.join(rel);
        let current = std::fs::read_to_string(&path).unwrap_or_default();
        if current == text {
            continue;
        }
        if check {
            stale.push(rel);
        } else {
            if let Some(dir) = path.parent() {
                std::fs::create_dir_all(dir).map_err(|e| e.to_string())?;
            }
            std::fs::write(&path, text).map_err(|e| format!("{rel}: {e}"))?;
            println!("    wrote {rel}");
        }
    }
    if stale.is_empty() {
        Ok(())
    } else {
        Err(format!("{} out of date; run `cargo xtask api` and commit the result", stale.join(", ")))
    }
}

/// `view.camera.preset` -> `view_camera_preset`
pub fn method_name(id: &str) -> String {
    id.replace(['.', '-'], "_")
}

fn available(c: &CommandSpec) -> bool {
    (c.enabled)(&Session::new()) || (c.enabled)(&Session::with_sample())
}

fn py_type(p: &Param) -> String {
    match p.kind {
        ParamKind::Str => "str".into(),
        ParamKind::Bool => "bool".into(),
        ParamKind::Number { .. } | ParamKind::Length { .. } | ParamKind::Rate { .. } => "float".into(),
        ParamKind::Integer { .. } => "int".into(),
        ParamKind::Choice(choices) => {
            format!("Literal[{}]", choices.iter().map(|c| format!("{c:?}")).collect::<Vec<_>>().join(", "))
        }
        ParamKind::Vec3 => "Sequence[float]".into(),
        ParamKind::StrList { .. } => "Sequence[str]".into(),
        ParamKind::PointList { .. } => "Sequence[Sequence[float]]".into(),
    }
}

fn range(p: &Param) -> String {
    match p.kind {
        ParamKind::Number { min, max } => format!(" ({} to {})", num(min), num(max)),
        ParamKind::Length { min, max } => format!(" ({} to {} mm)", num(min), num(max)),
        ParamKind::Rate { min, max } => format!(" ({} to {} mm/min)", num(min), num(max)),
        ParamKind::Integer { min, max } if max == i64::MAX => format!(" (≥ {min})"),
        ParamKind::Integer { min, max } => format!(" ({min} to {max})"),
        ParamKind::Choice(choices) => format!(" — one of {}", choices.join(", ")),
        ParamKind::Vec3 => " — [x, y, z] in mm".into(),
        ParamKind::PointList { .. } => " — [[x, y, z], …] in mm".into(),
        _ => String::new(),
    }
}

fn num(n: f64) -> String {
    if n.abs() >= 1.0e5 { format!("{n:e}") } else { format!("{n}") }
}

fn python(commands: &[&CommandSpec]) -> String {
    let mut out = String::new();
    out.push_str(
        "# Generated by `cargo xtask api` from the CosmicCAM command registry. Do not edit.\n\
         \"\"\"One method per CosmicCAM command. Mixed into :class:`cosmiccam.CosmicCAM`.\"\"\"\n\n\
         from __future__ import annotations\n\n\
         from typing import Any, Dict, Literal, Optional, Sequence\n\n\n\
         class Commands:\n    \
         \"\"\"Typed wrappers around :meth:`execute`. Each method runs the command of the same id.\"\"\"\n\n    \
         def execute(self, command: str, params: Optional[Dict[str, Any]] = None) -> Any:  # pragma: no cover\n        \
         raise NotImplementedError\n",
    );
    for c in commands {
        let mut sig = vec!["self".to_owned()];
        let required: Vec<&Param> = c.params.iter().filter(|p| p.required).collect();
        let optional: Vec<&Param> = c.params.iter().filter(|p| !p.required).collect();
        if !c.params.is_empty() {
            sig.push("*".into());
        }
        for p in &required {
            sig.push(format!("{}: {}", p.name, py_type(p)));
        }
        for p in &optional {
            sig.push(format!("{}: Optional[{}] = None", p.name, py_type(p)));
        }
        let _ = writeln!(out, "\n    def {}({}) -> Any:", method_name(c.id), sig.join(", "));
        let mut doc = format!("{}.", c.tooltip.trim_end_matches('.'));
        if !available(c) {
            doc.push_str(
                "\n\n        Planned: not available yet; calling it raises CosmicCAMError(kind=\"disabled\").",
            );
        }
        if !c.params.is_empty() {
            doc.push_str("\n\n        Args:");
            for p in c.params {
                let _ = write!(doc, "\n            {}: {}{}.", p.name, p.doc, range(p));
            }
        }
        let _ = write!(doc, "\n\n        Returns:\n            {}\n\n        Command: ``{}``", c.returns, c.id);
        let _ = writeln!(out, "        \"\"\"{doc}\n        \"\"\"");
        if c.params.is_empty() {
            let _ = writeln!(out, "        return self.execute({:?})", c.id);
        } else {
            let names: Vec<String> = c.params.iter().map(|p| format!("{0:?}: {0}", p.name)).collect();
            let _ = writeln!(out, "        params = {{{}}}", names.join(", "));
            let _ = writeln!(
                out,
                "        return self.execute({:?}, {{k: v for k, v in params.items() if v is not None}})",
                c.id
            );
        }
    }
    out
}

fn guide(intro: &str, commands: &[&CommandSpec]) -> String {
    let mut out = String::new();
    out.push_str("<!-- Generated by `cargo xtask api` from docs/api/_intro.md and the command registry. Edit those, not this file. -->\n\n");
    out.push_str(intro.trim_end());
    out.push_str("\n\n## Command reference\n\n");
    let mut areas: Vec<&str> = Vec::new();
    for c in commands {
        let area = c.id.split('.').next().unwrap_or_default();
        if !areas.contains(&area) {
            areas.push(area);
        }
    }
    let _ = writeln!(
        out,
        "{} commands in {} areas. Planned commands are listed so scripts can be written ahead; they raise `disabled` until their phase lands.\n",
        commands.len(),
        areas.len()
    );
    for area in &areas {
        let ids: Vec<String> = commands
            .iter()
            .filter(|c| c.id.split('.').next() == Some(area))
            .map(|c| format!("[`{0}`](#{1})", c.id, c.id.replace(['.'], "")))
            .collect();
        let _ = writeln!(out, "- **{area}**: {}", ids.join(", "));
    }
    for area in areas {
        let _ = writeln!(out, "\n### {area}\n");
        for c in commands.iter().filter(|c| c.id.split('.').next() == Some(area)) {
            let _ = writeln!(out, "#### `{}`\n", c.id);
            let call: Vec<String> = c
                .params
                .iter()
                .map(|p| if p.required { format!("{}=…", p.name) } else { format!("{}=None", p.name) })
                .collect();
            let _ = writeln!(out, "```python\ncc.{}({})\n```\n", method_name(c.id), call.join(", "));
            let _ = writeln!(out, "{}.", c.tooltip.trim_end_matches('.'));
            if !available(c) {
                out.push_str(" **Planned — not available yet.**");
            }
            out.push('\n');
            if !c.params.is_empty() {
                out.push_str("\n| Parameter | Type | Required | Description |\n| --- | --- | --- | --- |\n");
                for p in c.params {
                    let _ = writeln!(
                        out,
                        "| `{}` | {} | {} | {}{} |",
                        p.name,
                        p.kind.type_name(),
                        if p.required { "yes" } else { "no" },
                        p.doc,
                        range(p)
                    );
                }
            }
            let _ = writeln!(out, "\nReturns: {}", c.returns.replace('|', "\\|"));
            let mut extra = Vec::new();
            if let Some(s) = c.shortcut {
                extra.push(format!("shortcut `{s}`"));
            }
            if let Some(p) = c.placement {
                extra.push(format!("ribbon: {} › {}", p.tab.label(), p.panel));
            }
            if !extra.is_empty() {
                let _ = writeln!(out, "\n<sub>{}</sub>", extra.join(" · "));
            }
            out.push('\n');
        }
    }
    out
}
